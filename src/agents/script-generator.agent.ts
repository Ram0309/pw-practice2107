import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { z } from 'zod';
import { relative, slugify, writeText } from '../core/artifacts.js';
import { PATHS } from '../core/paths.js';
import { toCode } from '../browser/locators.js';
import { invokeStructured } from '../llm/structured.js';
import { systemPrompt } from '../llm/prompts.js';
import { GeneratedScriptSchema, type GeneratedScript, type TestCase, type UiMap, type ValidationIssue } from '../schemas/index.js';
import { BaseAgent } from './base-agent.js';

/**
 * AGENT 5 — SCRIPT GENERATOR AGENT
 * --------------------------------
 * Test case → Playwright + TypeScript spec that uses the project's page objects
 * and fixtures. Output is written to generated-tests/<req>/ as a PROPOSAL.
 * It is never executed until the Code Validator approves it.
 *
 * On a retry it receives the validator's issues and must fix them.
 */
export interface ScriptGenInput {
  requirementId: string;
  module: string;
  testCase: TestCase;
  uiMap?: UiMap | null;
  previousIssues?: ValidationIssue[];
  attempt?: number;
}

const LlmScriptSchema = z.object({ code: z.string(), notes: z.array(z.string()) });
const FIXTURES_IMPORT = `import { test, expect } from '../../src/fixtures/test-fixtures.js';`;

export class ScriptGeneratorAgent extends BaseAgent<ScriptGenInput, GeneratedScript> {
  readonly name = 'scriptGenerator' as const;
  readonly description = 'Script Generator Agent: generate Playwright script';
  protected readonly outputSchema = GeneratedScriptSchema;

  protected async offline(input: ScriptGenInput): Promise<GeneratedScript> {
    const { body, notes } = templateBody(input.module, input.testCase);
    return this.save(input, wrap(input, body), 'template', notes);
  }

  protected async withLlm(input: ScriptGenInput): Promise<GeneratedScript> {
    const pageObjectApi = await readFile(path.join(PATHS.prompts, 'page-object-api.md'), 'utf8');
    const ui = input.uiMap
      ? input.uiMap.elements.slice(0, 60).map(e => `${e.role} "${e.name}" -> ${toCode(e.recommended)}`).join('\n')
      : 'not available';
    const result = await invokeStructured({
      agent: this.name,
      schema: LlmScriptSchema,
      schemaName: 'playwright_script',
      system: await systemPrompt('script-generator-agent'),
      user: [
        `TEST CASE:\n${JSON.stringify(input.testCase, null, 2)}`,
        `PAGE OBJECT API:\n${pageObjectApi}`,
        `OBSERVED UI ELEMENTS (verified locators):\n${ui}`,
        `REQUIRED FIRST LINE OF IMPORTS:\n${FIXTURES_IMPORT}`,
        `TEST TITLE MUST START WITH: ${input.testCase.id}`,
        input.previousIssues?.length
          ? `THE PREVIOUS ATTEMPT WAS REJECTED. FIX THESE ISSUES:\n${input.previousIssues.map(i => `- [${i.severity}] ${i.rule}: ${i.message}`).join('\n')}`
          : ''
      ].join('\n\n')
    });
    const code = result.code.replace(/^```(?:ts|typescript)?\s*|```\s*$/g, '').trim() + '\n';
    return this.save(input, code, 'llm', result.notes);
  }

  private async save(input: ScriptGenInput, code: string, generator: GeneratedScript['generator'], notes: string[]): Promise<GeneratedScript> {
    const fileName = `${slugify(input.testCase.id)}-${slugify(input.testCase.title, 40)}.spec.ts`.replace(/-+\.spec/, '.spec');
    const abs = await writeText(path.join(PATHS.generatedTests, slugify(input.requirementId), fileName), code);
    return { testCaseId: input.testCase.id, fileName, filePath: relative(abs), code, generator, attempt: input.attempt ?? 1, notes };
  }
}

// ───────────────────────────── deterministic templates ─────────────────────────────

const s = (v: string) => JSON.stringify(v);

function wrap(input: ScriptGenInput, body: string): string {
  const tc = input.testCase;
  const fixtures = ['homePage', 'searchPage', 'loginPage', 'productPage', 'cartPage', 'data', 'page'].filter(f =>
    new RegExp(`\\b${f}\\b`).test(body)
  );
  return `/**
 * AUTO-GENERATED by AI-QA-AGENT-FRAMEWORK (Script Generator Agent)
 * Requirement: ${input.requirementId} | Test case: ${tc.id} | Covers: ${tc.acceptanceCriteria.join(', ')}
 * Expected: ${tc.expectedResult.replace(/\*\//g, '* /')}
 * Status: PROPOSAL. Review before promoting to tests/ui.
 */
${FIXTURES_IMPORT}

test(${s(`${tc.id} ${tc.title} ${tc.tags.join(' ')}`)}, async ({ ${fixtures.join(', ')} }) => {
${body
  .split('\n')
  .map(l => (l ? `  ${l}` : l))
  .join('\n')}
});
`;
}

export function templateBody(module: string, tc: TestCase): { body: string; notes: string[] } {
  const d = tc.testData;
  const expected = tc.expectedResult.toLowerCase();
  const lines: string[] = [];
  const notes: string[] = [];

  switch (module) {
    case 'Product Search': {
      lines.push('await homePage.goto();', `await homePage.search(${s(d.input ?? 'laptop')});`);
      if (d.absentText) lines.push(`await expect(searchPage.results).not.toContainText(${s(d.absentText)});`);
      else if (d.expectedText && d.expectedText.split(' ').length >= 4) lines.push(`await searchPage.expectMessage(${s(d.expectedText)});`);
      else if (d.expectedText) lines.push(`await searchPage.expectProductListed(${s(d.expectedText)});`);
      else if (/price|add to cart/.test(expected)) {
        lines.push(
          'const first = searchPage.productItems.first();',
          "await expect(first.locator('.product-title a')).toBeVisible();",
          "await expect(first.locator('.prices')).toBeVisible();",
          "await expect(first.getByRole('button', { name: 'Add to cart' })).toBeVisible();"
        );
      } else lines.push('await expect(searchPage.productItems.first()).toBeVisible();');
      break;
    }
    case 'Shopping Cart': {
      lines.push(`await searchPage.goto(${s(d.searchTerm ?? 'laptop')});`, 'await searchPage.expectCartCount(0);', `await searchPage.addToCart(${s(d.product ?? '14.1-inch Laptop')});`);
      let asserted = false;
      if (/notification|has been added/.test(expected)) { lines.push('await searchPage.expectNotification(data.messages.addedToCart);'); asserted = true; }
      if (/counter|\(1\)/.test(expected)) { lines.push('await searchPage.expectCartCount(1);'); asserted = true; }
      if (/cart page|quantity 1|lists/.test(expected)) { lines.push('await cartPage.goto();', `await cartPage.expectProduct(${s(d.product ?? '14.1-inch Laptop')}, 1);`); asserted = true; }
      if (/line total|multiplied|subtotal/.test(expected)) {
        lines.push('await searchPage.expectCartCount(1);', 'await cartPage.goto();', `const [unit, qty, total] = await cartPage.lineValues(${s(d.product ?? '14.1-inch Laptop')});`, 'expect(total).toBeCloseTo(unit * qty, 2);');
        asserted = true;
      }
      if (!asserted) lines.push('await searchPage.expectNotification(data.messages.addedToCart);');
      break;
    }
    case 'Customer Login': {
      if (/registered customer with a valid/.test(expected) || /logged in/.test(expected)) {
        notes.push('Needs a registered account supplied as a CI secret; generated as fixme.');
        return { body: "test.fixme(true, 'Requires a registered test account supplied via CI secrets');", notes };
      }
      lines.push('await loginPage.goto();', `await loginPage.login(${s(d.email ?? '')}, data.login.anyPassword);`);
      if (d.expectedText) lines.push(`await expect(page.getByText(${s(d.expectedText)})).toBeVisible();`);
      break;
    }
    default:
      notes.push(`No template for module "${module}"; generated as fixme with manual steps.`);
      return {
        body: [`test.fixme(true, 'No automation template for module ${module.replace(/'/g, '')}');`, ...tc.steps.map((st, i) => `// ${i + 1}. ${st.action}${st.expected ? ` -> ${st.expected}` : ''}`)].join('\n'),
        notes
      };
  }
  return { body: lines.join('\n'), notes };
}

export const scriptGeneratorAgent = new ScriptGeneratorAgent();
